import { describe, expect, it } from 'vitest';
import { render } from 'vitest-browser-svelte';
import { expectAccessible } from '../../testing/helpers';
import TermsContent from './TermsContent.svelte';

describe('TermsContent', () => {
	it('states the no-AI rule, the license, and conduct rules', async () => {
		const screen = await render(TermsContent, { appName: 'MinnowPress' });
		await expect
			.element(screen.getByRole('heading', { name: '1. Write it yourself' }))
			.toBeInTheDocument();
		await expect
			.element(screen.getByText(/Don't publish text generated by AI\s+tools/))
			.toBeInTheDocument();
		await expect.element(screen.getByRole('link', { name: 'CC BY-SA 4.0' })).toBeInTheDocument();
		await expect.element(screen.getByRole('heading', { name: '3. Be kind' })).toBeInTheDocument();
		await expectAccessible(screen.container);
	});
});
